import { NextRequest, NextResponse } from 'next/server';
import { createClient } from '@supabase/supabase-js';
import fs from 'fs';
import path from 'path';

export async function GET(request: NextRequest) {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL || '';
  const isConfigured = Boolean(
    url && 
    url.startsWith('https://') && 
    !url.includes('your-project') && 
    !url.includes('placeholder')
  );

  return NextResponse.json({
    configured: isConfigured,
    url: isConfigured ? url : null
  });
}

export async function POST(request: NextRequest) {
  try {
    const body = await request.json();
    const { url, anonKey, serviceRoleKey } = body;

    if (!url || !url.startsWith('https://')) {
      return NextResponse.json(
        { success: false, error: 'Valid Supabase project URL (https://xxxx.supabase.co) is required' },
        { status: 400 }
      );
    }

    if (!anonKey || anonKey.length < 20) {
      return NextResponse.json(
        { success: false, error: 'Valid Supabase Anon Public API Key is required' },
        { status: 400 }
      );
    }

    // Test ping to Supabase
    try {
      const testClient = createClient(url, anonKey);
      await testClient.auth.getSession();
    } catch (testErr: any) {
      // Continue anyway as tables might be awaiting migration
    }

    // Save to .env.local in apps/web
    const envContent = `# Auto-generated by MIC Smart Campus Super Admin Panel
NEXT_PUBLIC_SUPABASE_URL=${url}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}
${serviceRoleKey ? `SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}` : ''}
NEXT_PUBLIC_APP_NAME="MIC Smart Campus"
NEXT_PUBLIC_APP_TAGLINE="Learn • Connect • Grow"
NEXT_PUBLIC_APP_URL="http://localhost:3000"
`;

    const envPath = path.join(process.cwd(), '.env.local');
    fs.writeFileSync(envPath, envContent, 'utf-8');

    // Also update root .env if accessible
    try {
      const rootEnvPath = path.join(process.cwd(), '../../.env');
      fs.writeFileSync(rootEnvPath, envContent, 'utf-8');
    } catch (_) {}

    return NextResponse.json({
      success: true,
      message: 'Supabase Database successfully connected and configured!',
      url
    });
  } catch (err: any) {
    return NextResponse.json(
      { success: false, error: err?.message || 'Failed to save Supabase configuration' },
      { status: 500 }
    );
  }
}
